# ---- tokens ----
def words(text):
    """Lower-case purpose words of identifiers and prose: snake and camel case split, stop words and digits out,
    a plural `s` cut so `refusals` and `refusal` meet."""
    out = []
    for w in re.findall(r"[A-Za-z][A-Za-z0-9]*", re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", text or "")):
        w = w.lower()
        if len(w) < 2 or w in STOP or w.isdigit():
            continue
        if len(w) > 4 and w.endswith("sses"):
            w = w[:-2]
        elif len(w) > 3 and w.endswith("s") and not w.endswith("ss"):
            w = w[:-1]
        out.append(w)
    return out


def join(toks):
    """Signature tokens back to text: `&'a str`, `Result<u64, Refusal>`, `x: &Value`."""
    out, prev = "", ""
    for t in toks:
        wordy = bool(re.match(r"[\w']", t))
        if t == ",":
            out += ", "
        elif t == ":":
            out += ": "
        elif t in ("->", "=", "=>", "+", "|"):
            out = out.rstrip() + f" {t} "
        elif wordy and prev and (re.match(r"[\w']", prev[-1]) or prev in ("dyn",)):
            out += " " + t
        else:
            out += t
        prev = out[-1:] if out else ""
    return re.sub(r"\s+", " ", out).strip()


def norm_type(text, local=frozenset()):
    """A type as comparable tokens: lifetimes, `&`, `mut`, paths and generics' punctuation dropped; a type the
    item's own file defines privately keeps its file (`Query@read.rs`), so two files' own `Query` differ."""
    toks = []
    for w in re.findall(r"[A-Za-z_]\w*(?:::[A-Za-z_]\w*)*|'[A-Za-z_]\w*", text or ""):
        if w.startswith("'"):
            continue
        last = w.split("::")[-1]
        if last in ("mut", "dyn", "impl"):
            continue
        last = ALIAS.get(last, last)
        toks.append(f"{last}@{getattr(local, 'tag', '')}" if last in local else last)
    return toks


class Local(frozenset):
    """A file's private type names, tagged with the file so norm_type can mark them."""
    def __new__(cls, names, tag):
        obj = super().__new__(cls, names)
        obj.tag = tag
        return obj


# ---- Rust ----
def _vis(toks, i):
    """'pub' when the item whose keyword sits at toks[i] is pub (pub(crate) included), else ''."""
    j = i - 1
    while j >= 0:
        k, t, _ = toks[j]
        if k == "ident" and t in QUALS - {"pub"}:
            j -= 1
        elif k == "str":  # extern "C"
            j -= 1
        elif t == ")" and j >= 3 and toks[j - 2][1] == "(" and toks[j - 3][1] == "pub":
            return "pub"
        elif t == ")" and j >= 4 and toks[j - 3][1] == "(" and toks[j - 4][1] == "pub":  # pub(in path)
            return "pub"
        else:
            return "pub" if t == "pub" else ""
    return ""


def _angle_close(toks, i, stop):
    """Index of the `>` closing the `<` at toks[i] (a `->` is one token, so never miscounted)."""
    depth = 0
    for j in range(i, stop):
        t = toks[j][1]
        if t == "<":
            depth += 1
        elif t == ">":
            depth -= 1
            if not depth:
                return j
        elif t in ("{", ";"):
            return j - 1
    return stop - 1


def _split_params(toks):
    """[(name, type tokens)] of a fn's parameter list (the tokens inside its parens)."""
    parts, cur, depth = [], [], 0
    for t in toks:
        if t in ("(", "[", "<"):
            depth += 1
        elif t in (")", "]", ">"):
            depth -= 1
        if t == "," and depth == 0:
            parts.append(cur)
            cur = []
        else:
            cur.append(t)
    if cur:
        parts.append(cur)
    out = []
    for p in parts:
        if ":" in p:
            k = p.index(":")
            name = [x for x in p[:k] if x not in ("mut", "&")]
            out.append((name[-1] if name else "_", p[k + 1:]))
        elif p and p[-1] == "self":
            out.append(("self", p))
    return out


def _doc(lines, line):
    """(first doc line, doc paragraph) of the `///` (or `#` / `//` / `*`) comment just above 1-based line."""
    i, doc = line - 2, []
    while i >= 0:
        s = lines[i].strip()
        if s.startswith("///") or s.startswith("//!"):
            doc.append(s[3:].strip())
        elif s.startswith("#[") or s.startswith("#!") or (s.endswith(")]") and not s.startswith("//")) or \
                s.startswith("@") or s in ("]", ")]"):
            pass
        elif s.startswith("//"):
            if doc:
                break
        else:
            break
        i -= 1
    doc.reverse()
    para = []
    for d in doc:
        if not d or d.startswith("#"):
            break
        para.append(d)
    return (para[0] if para else ""), " ".join(para)


def _spans(toks, fns):
    """Containers: [(start, end, kind, owner, trait)] for impl and trait blocks, and fn bodies and test mods."""
    spans = [(a, b, "test", "", "") for a, b in rust_src.cfg_test_spans(toks)]
    spans += [(f["body"][0], f["body"][1], "body", "", "") for f in fns if f["body"]]
    for i, (k, t, _) in enumerate(toks):
        if k != "ident" or t not in ("impl", "trait") or (i and toks[i - 1][1] in ("&", "dyn", "->", "(", ",", "<")):
            continue
        j = i + 1
        while j < len(toks) and toks[j][1] not in ("{", ";"):
            if toks[j][1] == "<":
                j = _angle_close(toks, j, len(toks))
            j += 1
        if j >= len(toks) or toks[j][1] != "{":
            continue
        head = [x[1] for x in toks[i + 1:j]]
        if t == "trait":
            spans.append((j, rust_src.match_close(toks, j), "trait", head[0] if head else "", head[0] if head else ""))
            continue
        while head and head[0] == "<":  # impl<T> generics
            d, n = 0, 0
            for n, x in enumerate(head):
                d += {"<": 1, ">": -1}.get(x, 0)
                if d == 0:
                    break
            head = head[n + 1:]
        trait = ""
        if "for" in head:
            k2 = head.index("for")
            trait, head = join(head[:k2]), head[k2 + 1:]
        owner = next((x for x in head if re.match(r"[A-Za-z_]\w*$", x) and x not in ("dyn", "mut", "where")), "")
        if "::" in head[:4] and owner:  # crate::a::Type
            idents = [x for x in head if re.match(r"[A-Za-z_]\w*$", x)]
            owner = idents[min(len(idents) - 1, head[:head.index("<")].count("::") if "<" in head else
                               head.count("::"))] if idents else owner
        spans.append((j, rust_src.match_close(toks, j), "impl", owner, trait))
    return spans


def _inside(spans, i):
    """The innermost container span holding token i, or None."""
    best = None
    for s in spans:
        if s[0] < i < s[1] and (best is None or s[0] > best[0]):
            best = s
    return best


def rust_items(text, path):
    toks = rust_src.tokens(text)
    lines = text.splitlines()
    fns = rust_src.functions(toks)
    spans = _spans(toks, fns)
    out, fn_at = [], {f["start"]: f for f in fns}
    for i, (k, t, ln) in enumerate(toks):
        if k != "ident" or i + 1 >= len(toks):
            continue
        nxt = toks[i + 1]
        is_fn = t == "fn" and i in fn_at
        is_item = t in ITEM_KW and nxt[0] == "ident" and not (t == "const" and nxt[1] in ("fn", "unsafe", "async",
                                                                                        "extern"))
        is_macro = t == "macro_rules" and nxt[1] == "!" and i + 2 < len(toks)
        if not (is_fn or is_item or is_macro):
            continue
        if t == "type" and i and toks[i - 1][1] in ("<", ",", "("):
            continue
        box = _inside(spans, i)
        if box and box[2] in ("test", "body"):
            continue
        if is_fn and fn_at[i]["test"]:
            continue
        owner, trait = (box[3], box[4]) if box else ("", "")
        if box and box[2] == "impl" and trait and not is_fn:
            continue  # `type Item = ..` of a trait impl
        first, para = _doc(lines, ln)
        name = toks[i + 2][1] if is_macro else nxt[1]
        item = {"path": path, "line": ln, "name": name, "owner": owner, "trait": trait, "doc": first, "para": para,
                "vis": _vis(toks, i) or ("pub" if trait or (box and box[2] == "trait") else ""),
                "params": [], "ret": "", "sig": "", "body": set(), "self": False}
        if is_macro:
            item.update(kind="macro", sig="!")
        elif is_fn:
            f = fn_at[i]
            stop = f["body"][0] if f["body"] else next((j for j in range(i, len(toks)) if toks[j][1] == ";"),
                                                       len(toks))
            j = i + 2
            if j < stop and toks[j][1] == "<":
                j = _angle_close(toks, j, stop) + 1
            if j < stop and toks[j][1] == "(":
                close = rust_src.match_close(toks, j)
                params = _split_params([x[1] for x in toks[j + 1:close]])
                rest = [x[1] for x in toks[close + 1:stop]]
            else:
                params, rest = [], []
            if "where" in rest:
                rest = rest[:rest.index("where")]
            ret = join(rest[1:]) if rest[:1] == ["->"] else ""
            item.update(kind="fn" if not owner else ("trait fn" if box[2] == "trait" else "method"),
                        params=[(n, join(ty)) for n, ty in params], ret=ret,
                        self=any(n == "self" for n, _ in params),
                        sig="(" + ", ".join(join(ty) if n == "self" else f"{n}: {join(ty)}" for n, ty in params) + ")")
            if f["body"]:
                body = toks[f["body"][0]:f["body"][1]]
                item["body"] = {x[1] for x in body if x[0] == "ident"}
                item["stub"] = any(x[0] == "ident" and x[1] in STUB_MACROS for x in body) or                     any(x[0] == "str" and STUB_TEXT.search(x[1]) for x in body)
        else:
            stop = next((j for j in range(i + 2, min(len(toks), i + 400)) if toks[j][1] in ("{", ";", "=", "(")),
                        i + 2)
            if t in ("const", "static"):
                seg = [x[1] for x in toks[i + 2:stop]]
                item.update(kind=t, ret=join(seg[1:]) if seg[:1] == [":"] else "")
            else:
                gen = join([x[1] for x in toks[i + 2:stop]]) if stop > i + 2 and toks[i + 2][1] == "<" else ""
                item.update(kind=t, sig=gen)
        out.append(item)
    return out


# ---- Python ----
def python_items(text, path):
    try:
        tree = ast.parse(text)
    except (SyntaxError, ValueError):
        return []
    out = []

    def ann(a):
        try:
            return ast.unparse(a) if a is not None else ""
        except Exception:  # noqa: BLE001 (ast.unparse on odd nodes)
            return ""

    def visit(nodes, owner):
        for n in nodes:
            if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
                if n.name.startswith("test_") or "tests" in path.split("/")[:-1]:
                    continue
                doc = (ast.get_docstring(n) or "").strip()
                para = doc.split("\n\n")[0].replace("\n", " ")
                a = n.args
                params = [(x.arg, ann(x.annotation)) for x in a.posonlyargs + a.args + a.kwonlyargs]
                body = {x.id for x in ast.walk(n) if isinstance(x, ast.Name)} | \
                       {x.attr for x in ast.walk(n) if isinstance(x, ast.Attribute)}
                out.append({"path": path, "line": n.lineno, "name": n.name, "owner": owner, "trait": "",
                            "kind": "method" if owner else "fn", "doc": doc.splitlines()[0] if doc else "",
                            "para": para, "vis": "" if n.name.startswith("_") else "pub",
                            "params": [(p, t) for p, t in params if p not in ("self", "cls")],
                            "self": bool(owner) and bool(params) and params[0][0] in ("self", "cls"),
                            "sig": "(" + ", ".join(f"{p}: {t}" if t else p for p, t in params) + ")",
                            "ret": ann(n.returns), "body": body})
            elif isinstance(n, ast.ClassDef):
                doc = (ast.get_docstring(n) or "").strip()
                out.append({"path": path, "line": n.lineno, "name": n.name, "owner": owner, "trait": "",
                            "kind": "class", "doc": doc.splitlines()[0] if doc else "",
                            "para": doc.split("\n\n")[0].replace("\n", " "),
                            "vis": "" if n.name.startswith("_") else "pub", "params": [], "self": False,
                            "sig": "", "ret": "", "body": set()})
                if not owner:
                    visit(n.body, n.name)
    visit(tree.body, "")
    return out


# ---- JS / TS ----
JS_ITEM = re.compile(
    r"^[ \t]*(?P<exp>export\s+(?:default\s+)?)?(?:declare\s+)?(?:"
    r"(?:async\s+)?function\s*\*?\s*(?P<fn>[A-Za-z_$][\w$]*)\s*(?:<[^>(]*>)?\s*\((?P<fargs>[^)]*)\)\s*"
    r"(?::\s*(?P<fret>[^{=;]+?))?\s*[{;]"
    r"|(?:const|let|var)\s+(?P<arrow>[A-Za-z_$][\w$]*)\s*(?::[^=]+)?=\s*(?:async\s+)?"
    r"(?:\((?P<aargs>[^)]*)\)|(?P<one>[A-Za-z_$][\w$]*))\s*(?::\s*(?P<aret>[^=]+?))?\s*=>"
    r"|class\s+(?P<cls>[A-Za-z_$][\w$]*)"
    r"|interface\s+(?P<iface>[A-Za-z_$][\w$]*)"
    r"|type\s+(?P<alias>[A-Za-z_$][\w$]*)\s*(?:<[^>]*>)?\s*=)", re.M)


def js_items(text, path):
    out, lines = [], text.splitlines()
    for m in JS_ITEM.finditer(text):
        ln = text.count("\n", 0, m.start()) + 1
        kind = "fn" if (m.group("fn") or m.group("arrow")) else (
            "class" if m.group("cls") else "interface" if m.group("iface") else "type")
        name = m.group("fn") or m.group("arrow") or m.group("cls") or m.group("iface") or m.group("alias")
        args = m.group("fargs") if m.group("fn") else (m.group("aargs") or m.group("one") or "")
        params = []
        for p in re.split(r",(?![^<{\[]*[>}\]])", args or ""):
            p = p.strip()
            if p:
                n, _, ty = p.partition(":")
                params.append((n.strip().lstrip(".").rstrip("?").split("=")[0].strip(), ty.split("=")[0].strip()))
        doc = ""
        i = ln - 2
        while i >= 0 and lines[i].strip().startswith(("*", "/**", "*/", "//", "@")):
            s = lines[i].strip().lstrip("/*").strip()
            if s and not s.startswith("@"):
                doc = s
            i -= 1
        out.append({"path": path, "line": ln, "name": name, "owner": "", "trait": "", "kind": kind, "doc": doc,
                    "para": doc, "vis": "pub" if m.group("exp") else "", "params": params, "self": False,
                    "sig": f"({', '.join(f'{n}: {t}' if t else n for n, t in params)})" if kind == "fn" else "",
                    "ret": ((m.group("fret") or m.group("aret") or "").strip()), "body": set()})
    return out


PARSERS = {"rust": rust_items, "python": python_items, "js": js_items}


# ---- purpose and the INDEX lines ----
def purpose(item):
    """The words that say what an item is for: name, owner, doc paragraph, parameter names and types, return."""
    text = " ".join([item["name"], item["owner"], item["para"], " ".join(f"{n} {t}" for n, t in item["params"]),
                     item["ret"]])
    return sorted(set(words(text)))


def label(item):
    return f"{item['owner']}::{item['name']}" if item["owner"] else item["name"]


def line_of(item):
    """`path:line  kind name(signature) -> ret  // first doc line  [purpose: ..]`."""
    vis = "pub " if item["vis"] else ""
    sig = item["sig"] if item["kind"] in ("fn", "method", "trait fn") else (item["sig"] or "")
    ret = f" -> {item['ret']}" if item["ret"] else ""
    doc = f"  // {item['doc']}" if item["doc"] else ""
    return (f"{item['path']}:{item['line']}  {vis}{item['kind']} {label(item)}{sig}{ret}{doc}"
            f"  [purpose: {' '.join(purpose(item))}]")


def items_of(path, text):
    lang = EXTS.get(os.path.splitext(path)[1])
    if not lang:
        return []
    try:
        return PARSERS[lang](text, path)
    except RecursionError:
        return []


def _under(path, pats):
    for p in pats:
        p = p.strip().rstrip("/")
        if any(c in p for c in "*?["):
            import fnmatch
            if fnmatch.fnmatchcase(path, p):
                return True
        elif path == p or path.startswith(p + "/") or p in ("", "."):
            return True
    return False


def source_files(files, mods):
    """{module: [paths]} of the indexed source files (tests, fixtures, build output and generated files out)."""
    out = {m: [] for m in mods}
    for f in sorted(files):
        parts = f.split("/")
        if os.path.splitext(f)[1] not in EXTS or SKIP_DIRS & set(parts[:-1]) or "tests" in parts[:-1] \
                or "benches" in parts[:-1] or "examples" in parts[:-1]:
            continue
        for m, pats in mods.items():
            if _under(f, pats):
                out[m].append(f)
                break
    return out


def build(read, files, mods):
    """{module: [items]} for every module of mods ({module: [path patterns]}); read(path) returns the text."""
    out = {}
    for m, paths in source_files(files, mods).items():
        items = []
        for p in paths:
            items += items_of(p, read(p))
        items.sort(key=lambda it: (it["path"], it["line"], it["name"]))
        out[m] = items
    return out


def render(index, mods):
    """{relative path: text} of the INDEX files for index ({module: [items]})."""
    files, rows = {}, []
    for m in sorted(index):
        items = index[m]
        body = [HEADER, f"# INDEX {m}", "",
                f"{len(items)} items. Paths: {', '.join(mods.get(m, []))}. Search by purpose before writing a "
                f"function: `git grep -n -i -E \"<word>|<word>\" -- {INDEX_DIR}/`; reuse or extend the owner.", ""]
        cur = None
        for it in items:
            if it["path"] != cur:
                cur = it["path"]
                body += ["", f"## {cur}", ""]
            body.append(line_of(it))
        files[f"{INDEX_DIR}/{m}.md"] = "\n".join(body).rstrip() + "\n"
        rows.append(f"| {m} | {len(items)} | {sum(1 for i in items if i['vis'])} | [{INDEX_DIR}/{m}.md](index/{m}.md) |")
    files[SUMMARY] = "\n".join([HEADER, "# INDEX", "",
                                "Every item each module defines, public and private, is in its module's INDEX file. "
                                "Builders search these before writing any function (S6).", "",
                                "| module | items | pub | index |", "|---|---|---|---|", *rows]) + "\n"
    return files


# ---- reading a tree ----
def tree_reader(repo, rev=None):
    """(files, read) for the working tree (rev None) or a commit, read through one `git cat-file --batch`."""
    if rev is None:
        files = subprocess.run(["git", "ls-files", "-co", "--exclude-standard"], cwd=repo, capture_output=True,
                               text=True, encoding="utf-8", errors="replace").stdout.split("\n")
        files = [f for f in files if f and os.path.isfile(os.path.join(repo, f))]

        def read(p):
            with open(os.path.join(repo, p), encoding="utf-8", errors="replace") as fh:
                return fh.read()
        return files, read
    files = subprocess.run(["git", "ls-tree", "-r", "--name-only", rev], cwd=repo, capture_output=True, text=True,
                           encoding="utf-8", errors="replace").stdout.split("\n")
    files = [f for f in files if f and os.path.splitext(f)[1] in EXTS]
    blobs = cat_files(repo, rev, files)
    return files, lambda p: blobs.get(p, "")


def cat_files(repo, rev, paths):
    """{path: text} of paths at rev, in one git process."""
    if not paths:
        return {}
    inp = "".join(f"{rev}:{p}\n" for p in paths).encode("utf-8")
    raw = subprocess.run(["git", "cat-file", "--batch"], cwd=repo, input=inp, capture_output=True).stdout
    out, pos = {}, 0
    for p in paths:
        nl = raw.index(b"\n", pos)
        head = raw[pos:nl].split()
        pos = nl + 1
        if len(head) < 3 or head[1] == b"missing":
            continue
        size = int(head[2])
        out[p] = raw[pos:pos + size].decode("utf-8", "replace")
        pos += size + 1
    return out


def write(repo, mods, rev=None):
    """Regenerate the INDEX files in repo's working tree; return the relative paths written (stale ones removed)."""
    files, read = tree_reader(repo, rev)
    out = render(build(read, files, mods), mods)
    d = os.path.join(repo, INDEX_DIR)
    if os.path.isdir(d):
        for name in os.listdir(d):
            rel = f"{INDEX_DIR}/{name}"
            if name.endswith(".md") and rel not in out:
                os.remove(os.path.join(d, name))
    for rel, text in out.items():
        p = os.path.join(repo, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
    return sorted(out)


def regen_and_stage(repo, mods):
    """For land.py and plan_land.py: regenerate the INDEX files on the merged tree and `git add` them."""
    if not mods:
        return []
    paths = write(repo, mods)
    subprocess.run(["git", "add", "-A", "--", INDEX_DIR, SUMMARY], cwd=repo, capture_output=True)
    return paths


# ---- the semantic duplicate gate ----
def comparable(item):
    """A function the gate compares: free or associated (no self), not a trait impl or test, name not generic."""
    return item["kind"] in ("fn", "method") and not item["self"] and not item.get("stub") and not item["trait"] and \
        item["name"] not in COMMON and not item["name"].startswith("test")


TYPE_KINDS = ("struct", "enum", "type", "class", "interface", "trait", "union")


def _locals(items):
    """{path: Local(private type names of that file)}."""
    out = {}
    for it in items:
        if it["kind"] in TYPE_KINDS and not it["vis"]:
            out.setdefault(it["path"], set()).add(it["name"])
    return {p: Local(n, p.rsplit("/", 1)[-1]) for p, n in out.items()}


def _own_types(items):
    """{path: every type name that file defines, pub or not}."""
    out = {}
    for it in items:
        if it["kind"] in TYPE_KINDS:
            out.setdefault(it["path"], set()).add(it["name"])
    return out


class Profile:
    """One function's comparable features."""
    __slots__ = ("item", "purpose", "params", "ret", "name", "body", "own", "plain", "sig")

    def __init__(self, item, local, own=None):
        lc = local.get(item["path"], frozenset())
        self.item = item
        self.purpose = set(purpose(item))
        self.params = Counter(" ".join(norm_type(t, lc)) for n, t in item["params"])
        self.ret = norm_type(item["ret"].replace("Self", item["owner"] or "Self"), lc)
        self.name = item["name"]
        self.body = {ALIAS.get(w, w) for w in item["body"]} - BODY_STOP - {item["name"]}
        self.plain = [t.split("@")[0] for t in self.ret]
        self.own = bool(set(self.plain) & (own or {}).get(item["path"], set()))  # returns its own file's type
        self.sig = (tuple(sorted(self.params.elements())), tuple(self.plain))


def conventions(profiles):
    """Names defined in CONVENTION_FILES or more files of one directory: sibling plugins (each table source's
    `open`, each op's `apply`) implement one interface by convention; two of them are not duplicates of each other."""
    seen = {}
    for p in profiles:
        d = p.item["path"].rsplit("/", 1)[0]
        seen.setdefault((d, p.name), set()).add(p.item["path"])
    return {k for k, v in seen.items() if len(v) >= CONVENTION_FILES}


def sibling_convention(a, b, conv):
    d = a.item["path"].rsplit("/", 1)[0]
    return a.name == b.name and d == b.item["path"].rsplit("/", 1)[0] and (d, a.name) in conv


def idf_of(profiles):
    n = max(1, len(profiles))
    df = Counter(w for p in profiles for w in p.purpose)
    return lambda w: math.log(1 + n / (1 + df[w]))


def parts(a, b, idf, names):
    """(purpose, signature, body, name) similarities of two Profiles, each 0..1."""
    inter = sum(idf(w) for w in a.purpose & b.purpose)
    union = sum(idf(w) for w in a.purpose | b.purpose) or 1.0
    pa, pb = a.params, b.params
    n = sum((pa | pb).values())
    ptypes = sum((pa & pb).values()) / n if n else 1.0
    ra, rb = set(a.ret), set(b.ret)
    if a.ret == b.ret:
        ret = 1.0
    elif any("@" in t for t in ra ^ rb):
        ret = 0.0  # one returns its file's own private type: never the other's reuse target
    else:
        ret = len(ra & rb) / len(ra | rb) if ra | rb else 0.0
    body = len(a.body & b.body) / len(a.body | b.body) if a.body and b.body else 0.0
    same = 0.0
    if a.name == b.name:
        same = (1.0 if re.search(r"_|[a-z][A-Z]", a.name) else 0.5) / max(1, names[a.name] - 1)
    return inter / union, 0.5 * ptypes + 0.5 * ret, body, same


def score(a, b, idf, names, sigs=None):
    """0..1 how strongly a and b do the same job, the stronger of two readings (STANDARDS S50: name tokens or body):
    content: IDF-weighted purpose-token overlap (W_PURPOSE), the normalized signature (W_SIG: parameter types as a
    multiset, the return type) and the identifiers the bodies use (W_BODY); name: the same name, full for a
    compound name (`text_param`) only these two share, half for one word, scaled by 0.5 + (signature + purpose) / 4,
    the signature discounted by how common it is in the tree (`(&str) -> bool` says little). Only free functions
    match by name, and never one returning a type its own file defines when the other returns something else
    (`kind_param -> Kind`). A function returning its file's private type is never a match (two files' `parse_query
    -> Query` each build their own)."""
    if any("@" in t for t in set(a.ret) ^ set(b.ret)):
        return 0.0  # one returns its own file's private type: the other cannot call it for its own
    p, sig, body, same = parts(a, b, idf, names)
    content = W_PURPOSE * p + W_SIG * sig + W_BODY * body
    name = 0.0
    if same and not (a.item["owner"] or b.item["owner"]) and not ((a.own or b.own) and a.plain != b.plain):
        rare = 1.0 / (1.0 + math.log(min(sigs[a.sig], sigs[b.sig]))) if sigs else 1.0
        name = same * (0.5 + 0.25 * sig * rare + 0.25 * p)
    return round(max(content, name), 3)


def dups(new_items, base_items, threshold=DUP_SEMANTIC_MIN, gone=()):
    """[(new item, base item, score)] for each new function whose best match in base scores >= threshold.
    gone: (path, label) pairs the change removes, never a reuse target."""
    gone = set(gone)
    allitems = list(base_items) + list(new_items)
    local, own = _locals(allitems), _own_types(allitems)
    base = [Profile(it, local, own) for it in base_items if comparable(it) and (it["path"], label(it)) not in gone]
    news = [Profile(it, local, own) for it in new_items if comparable(it)]
    idf = idf_of(base + news)
    names = Counter(p.name for p in base + news)
    sigs = Counter(p.sig for p in base + news)
    conv = conventions(base + news)
    out = []
    for a in news:
        best = None
        for b in base:
            if b.item["path"] == a.item["path"] and b.name == a.name or sibling_convention(a, b, conv):
                continue
            if not (a.purpose & b.purpose) and a.name != b.name:
                continue
            s = score(a, b, idf, names, sigs)
            if best is None or s > best[2]:
                best = (a.item, b.item, s)
        if best and best[2] >= threshold:
            out.append(best)
    return out


def pairs(items, top=40):
    """The strongest cross-item pairs of one tree (each item scored against every other): threshold tuning."""
    local, own = _locals(items), _own_types(items)
    profs = [Profile(it, local, own) for it in items if comparable(it)]
    idf = idf_of(profs)
    names = Counter(p.name for p in profs)
    sigs = Counter(p.sig for p in profs)
    conv = conventions(profs)
    by_word = {}
    for k, p in enumerate(profs):
        for w in p.purpose:
            by_word.setdefault(w, []).append(k)
    seen, out = set(), []
    common = len(profs) // 20 or 1
    for k, a in enumerate(profs):
        cands = {j for w in a.purpose if len(by_word[w]) <= common for j in by_word[w] if j > k}
        cands |= {j for j, b in enumerate(profs) if j > k and b.name == a.name}
        for j in cands:
            b = profs[j]
            if (k, j) in seen or (a.item["path"] == b.item["path"] and a.name == b.name) or                     sibling_convention(a, b, conv):
                continue
            seen.add((k, j))
            out.append((score(a, b, idf, names, sigs), a.item, b.item))
    out.sort(key=lambda x: (-x[0], x[1]["path"], x[1]["line"]))
    return out[:top]


_AT = {}  # (repo, rev, modules) -> {module: [items]}: one parse per main sha


def index_at(repo, rev, mods):
    """{module: [items]} of the tree at commit rev, cached per (repo, rev)."""
    key = (os.path.abspath(repo), rev, tuple(sorted((m, tuple(p)) for m, p in mods.items())))
    if key not in _AT:
        if len(_AT) > 4:
            _AT.clear()
        files, read = tree_reader(repo, rev)
        _AT[key] = build(read, files, mods)
    return _AT[key]


def semantic_problem(repo, base_rev, head_rev, changed, mods, threshold=DUP_SEMANTIC_MIN):
    """Why head's new functions duplicate one base already has, or ''. changed: the files the change touches.
    A function is new when its file at head defines it and the same file at base does not; one the change removes
    from base is never named for reuse (a move is not a duplicate)."""
    changed = [p for p in changed if os.path.splitext(p)[1] in EXTS]
    if not changed or not mods:
        return ""
    base = [it for v in index_at(repo, base_rev, mods).values() for it in v]
    head_text = cat_files(repo, head_rev, changed)
    srcs = {p for v in source_files(head_text, mods).values() for p in v}
    head = [it for p in sorted(srcs) for it in items_of(p, head_text[p])]
    had = {(it["path"], label(it)) for it in base}
    now = {(it["path"], label(it)) for it in head}
    new = [it for it in head if (it["path"], label(it)) not in had]
    gone = {(it["path"], label(it)) for it in base if it["path"] in changed and (it["path"], label(it)) not in now}
    hits = dups(new, base, threshold, gone)
    if not hits:
        return ""
    names = "; ".join(f"new `{label(a)}` ({a['path']}:{a['line']}) does what `{b['path']}::{label(b)}` "
                      f"(line {b['line']}) does, score {s:.2f}: reuse {b['path']}::{label(b)} or extend it"
                      for a, b, s in hits[:5])
    return (f"semantic duplicate (dup_semantic_min {threshold:g}): {names}. Search spec/index/ by purpose before "
            "writing a function; a new helper whose job an indexed one does is a review FAIL (C05)")


# ---- ranking for the briefs ----
def ranked(items, text, top=40):
    """The INDEX lines of items most related to text (a row and its acceptance test), by IDF-weighted overlap of
    purpose tokens; ties keep index order. Only items sharing at least one word are listed."""
    want = set(words(text))
    profs = [(it, set(purpose(it))) for it in items]
    n = max(1, len(profs))
    df = Counter(w for _, ws in profs for w in ws)
    scored = []
    for k, (it, ws) in enumerate(profs):
        s = sum(math.log(1 + n / (1 + df[w])) for w in ws & want)
        if s > 0:
            scored.append((-s, k, it))
    scored.sort(key=lambda x: (x[0], x[1]))
    return [line_of(it) for _, _, it in scored[:top]]


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    repo = argv.pop(0) if argv and not argv[0].startswith("--") else "."
    import land  # the CLI only: land.py's ARCHITECTURE parser, one copy
    apath = os.path.join(repo, "spec", "ARCHITECTURE.md")
    with open(apath, encoding="utf-8") as fh:
        mods = land.module_paths(fh.read())
    if "--pairs" in argv:
        files, read = tree_reader(repo)
        items = [it for v in build(read, files, mods).values() for it in v]
        for s, a, b in pairs(items, int(argv[argv.index("--pairs") + 1])):
            print(f"{s:.3f}  {a['path']}:{a['line']} {label(a)}  ~  {b['path']}:{b['line']} {label(b)}")
        return 0
    if "--check" in argv:
        files, read = tree_reader(repo)
        out = render(build(read, files, mods), mods)
        stale = [p for p, t in out.items() if not os.path.isfile(os.path.join(repo, p))
                 or open(os.path.join(repo, p), encoding="utf-8").read() != t]
        print("INDEX OK" if not stale else f"INDEX stale: {', '.join(stale)} (run index_api.py; never edit by hand)")
        return 1 if stale else 0
    paths = write(repo, mods)
    print(f"wrote {len(paths)} INDEX files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
